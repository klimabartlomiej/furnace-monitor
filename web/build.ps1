# Packs the web app into ..\WebApp.h for the firmware:
#   index.html -> gzip                         -> WEBAPP_HTML_GZ, WEBAPP_ETAG (hash of it)
#   app icon   -> drawn here, 180x180 PNG      -> WEBAPP_ICON_PNG   (iPhone "Add to Home Screen")
#   manifest   -> WEBAPP_MANIFEST
# Run after every change of index.html:  powershell -ExecutionPolicy Bypass -File web\build.ps1

$ErrorActionPreference = 'Stop'
$sketch = Split-Path -Parent $PSScriptRoot

function Get-Gzip([byte[]]$data) {
  $ms = New-Object IO.MemoryStream
  $gz = New-Object IO.Compression.GZipStream($ms, [IO.Compression.CompressionLevel]::Optimal)
  $gz.Write($data, 0, $data.Length)
  $gz.Close()
  return , $ms.ToArray()
}

function New-Brush([int]$y0, [int]$y1, [int[]]$from, [int[]]$to) {
  New-Object Drawing.Drawing2D.LinearGradientBrush(
    (New-Object Drawing.Point 0, $y0), (New-Object Drawing.Point 0, $y1),
    [Drawing.Color]::FromArgb(255, $from[0], $from[1], $from[2]),
    [Drawing.Color]::FromArgb(255, $to[0], $to[1], $to[2]))
}

# A flame on a dark, warm gradient.
function Get-IconPng {
  Add-Type -AssemblyName System.Drawing
  $size = 180
  $bmp = New-Object Drawing.Bitmap $size, $size
  $g = [Drawing.Graphics]::FromImage($bmp)
  $g.SmoothingMode = 'AntiAlias'
  $g.FillRectangle((New-Brush 0 $size @(64, 26, 10) @(11, 13, 16)), 0, 0, $size, $size)

  $outer = New-Object Drawing.Drawing2D.GraphicsPath
  $outer.AddBezier(90, 154, 52, 154, 32, 126, 42, 96)
  $outer.AddBezier(42, 96, 48, 79, 61, 71, 63, 50)
  $outer.AddBezier(63, 50, 80, 61, 88, 76, 86, 94)
  $outer.AddBezier(86, 94, 99, 79, 105, 56, 96, 26)
  $outer.AddBezier(96, 26, 129, 49, 150, 84, 141, 117)
  $outer.AddBezier(141, 117, 135, 141, 116, 154, 90, 154)
  $outer.CloseFigure()
  $g.FillPath((New-Brush 26 154 @(255, 59, 48) @(255, 179, 64)), $outer)

  $inner = New-Object Drawing.Drawing2D.GraphicsPath
  $inner.AddBezier(90, 147, 70, 147, 61, 129, 67, 114)
  $inner.AddBezier(67, 114, 73, 101, 86, 97, 90, 82)
  $inner.AddBezier(90, 82, 107, 97, 117, 112, 113, 127)
  $inner.AddBezier(113, 127, 110, 141, 100, 147, 90, 147)
  $inner.CloseFigure()
  $g.FillPath((New-Brush 82 147 @(255, 214, 10) @(255, 246, 214)), $inner)

  $g.Dispose()
  $ms = New-Object IO.MemoryStream
  $bmp.Save($ms, [Drawing.Imaging.ImageFormat]::Png)
  $bmp.Dispose()
  return , $ms.ToArray()
}

function Format-CArray([string]$name, [byte[]]$bytes) {
  $sb = New-Object Text.StringBuilder
  [void]$sb.AppendLine("static const uint8_t $name[] PROGMEM = {")
  $hex = [string[]]($bytes | ForEach-Object { '0x{0:x2}' -f $_ })
  for ($i = 0; $i -lt $hex.Length; $i += 24) {
    $end = [Math]::Min($i + 23, $hex.Length - 1)
    [void]$sb.AppendLine('  ' + ($hex[$i..$end] -join ',') + ',')
  }
  [void]$sb.AppendLine('};')
  [void]$sb.AppendLine("static const size_t ${name}_LEN = sizeof($name);")
  return $sb.ToString()
}

$html = Get-Gzip ([IO.File]::ReadAllBytes("$PSScriptRoot\index.html"))
$icon = Get-IconPng
[IO.File]::WriteAllBytes("$PSScriptRoot\icon.png", $icon)   # preview copy, not used by the build

$manifest = '{"name":"Piec","short_name":"Piec","start_url":"/","display":"standalone","lang":"pl",' +
            '"background_color":"#0b0d10","theme_color":"#0b0d10",' +
            '"icons":[{"src":"/icon.png","sizes":"180x180","type":"image/png"}]}'

# ETag of the page: the phone keeps its copy and gets "304 Not Modified" until the page changes.
$sha = [Security.Cryptography.SHA1]::Create()
$etag = (($sha.ComputeHash($html) | Select-Object -First 6 | ForEach-Object { '{0:x2}' -f $_ }) -join '')

$out = "// Generated by web/build.ps1 from web/index.html - edit the source and rerun the script, not this file.`n" +
       "#pragma once`n#include <pgmspace.h>`n`n" +
       (Format-CArray 'WEBAPP_HTML_GZ' $html) + "`n" +
       "static const char WEBAPP_ETAG[] = `"\`"$etag\`"`";`n`n" +
       (Format-CArray 'WEBAPP_ICON_PNG' $icon) + "`n" +
       "static const char WEBAPP_MANIFEST[] PROGMEM = R`"json($manifest)json`";`n"
[IO.File]::WriteAllText("$sketch\WebApp.h", $out, (New-Object Text.UTF8Encoding $false))

"index.html gz: {0:N0} B, icon: {1:N0} B -> WebApp.h" -f $html.Length, $icon.Length
